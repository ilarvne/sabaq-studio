const roots = {catalog:catalogRoot,generated:defaultMediaRoot};

test('the editor API creates an idempotent fitted language version, reports slide correspondence and aligns changed structure on request', async t=>{
  const app = createStudioServer({dbPath:':memory:'});
  t.after(()=>app.close());
  const read = async (id:string)=>(await app.inject({url:'/api/decks/'+id})).json<Deck>();
  const original = await read('schoolyard-en');
  const path = '/api/decks/'+original.id;
  const target = makeFixtureDeck('kk');
  const payload = {language:'kk',baseRevision:original.revision,requestId:randomUUID()};
  const create = ()=>app.inject({method:'POST',url:path+'/language-versions',payload});
  const response = await create();
  assert.equal(response.statusCode,201,response.body.slice(0,500));
  const clone = response.json<Deck>();
  assert.equal(clone.qualityReview?.state, 'pending');
  assert.notEqual(clone.id,original.id);
  assert.equal(clone.translation!.checkedSlides,10);
  assert.equal(clone.title,target.title);
  assert.deepEqual(clone.slides.map(s=>s.notes),target.slides.map(s=>s.notes));
  assert.deepEqual(clone.slides.map(s=>s.id),original.slides.map(s=>s.id));
  assert.deepEqual(clone.source,original.source);
  assert.deepEqual(clone.slides.map(s=>s.evidence),original.slides.map(s=>s.evidence));
  assert.deepEqual(await read(original.id),original);
  assert.equal((await create()).json<Deck>().id,clone.id);
  const clonePath = '/api/decks/'+clone.id;
  const current = (await app.inject({method:'PATCH',url:clonePath,payload:{op:{kind:'slide',slideId:'s01',baseVersion:0,changes:{notes:'Мұғалімнің өз жазбасы.'}}}})).json<Deck>();
  const added = (await app.inject({method:'PATCH',url:path,payload:{op:{kind:'duplicate',slideId:'s01'}}})).json<Deck>();
  const versions = (await app.inject({url:clonePath+'/language-versions'})).json<RelatedVersion[]>();
  assert.equal(versions[0].added,1);
  assert.equal(versions[0].removed,0);
  assert.deepEqual((await read(clone.id)).slides,current.slides);
  const aligned = await app.inject({method:'POST',url:clonePath+'/language-versions/align',payload:{requestId:randomUUID(),baseRevision:current.revision,sourceId:original.id,sourceRevision:added.revision}});
  assert.equal(aligned.statusCode,200,aligned.body.slice(0,400));
  const matched=aligned.json<Deck>();
  assert.equal(matched.qualityReview?.state, 'pending');
  if (clone.qualityReview?.state === 'pending' && matched.qualityReview?.state === 'pending') assert.notEqual(matched.qualityReview.key, clone.qualityReview.key);
  assert.deepEqual(matched.slides.map(s=>s.id),added.slides.map(s=>s.id));
  assert.equal(matched.slides[0].notes,'Мұғалімнің өз жазбасы.');
  assert.equal(matched.slides[1].notes,target.slides[0].notes);
  const saved = (await app.inject({url:clonePath+'/language-versions/comparison'})).json<VersionComparison>();
  assert.equal(saved.slides.length,original.slides.length);
  assert.equal(saved.slides[0].before.notes,original.slides[0].notes);
  assert.equal(saved.slides[0].after.notes,target.slides[0].notes);
});

test('custom local translation copies formatted spans and numeric/chart/source data and rejects corrupted literal values', async t=>{
  const prior = process.env.STUDIO_TRANSLATION_OLLAMA_MODEL;
  process.env.STUDIO_TRANSLATION_OLLAMA_MODEL='translation-test';
  t.after(()=>{if (prior === undefined) delete process.env.STUDIO_TRANSLATION_OLLAMA_MODEL; else process.env.STUDIO_TRANSLATION_OLLAMA_MODEL=prior;});
  const d = makeFixtureDeck('en');
  d.qualityReview = { state: 'reviewed', theme: d.theme, slides: {} };
  const s = d.slides[0]; d.slides=[s];d.outline=[d.outline[0]];
  s.title='Measuring sand';s.notes='Read 25 units at https://example.org/probe';s.body='Weigh 25 grains.';
  const href='https://example.org/lab?q=2';
  s.richText={body:{type:'doc',content:[{type:'paragraph',content:[{type:'text',text:'Weigh ',marks:[{type:'bold'}]},{type:'text',text:'25 grains.',marks:[{type:'link',attrs:{href}}]}]}]}};
  s.bodyRuns=[{text:'Weigh ',bold:true},{text:'25 grains.',href}];
  let corrupt=false;
  const ru: Record<string,string> = {'Measuring sand':'Измерение песка','Read 25 units at https://example.org/probe':'Прочитайте 25 единиц на https://example.org/probe',Weigh:'Взвесьте','25 grains.':'25 зёрен.'};
  const worker=t.mock.method(globalThis,'fetch',async (url:URL,init:RequestInit)=>{
    assert.equal(url.hostname,'127.0.0.1');
    if (url.pathname === '/api/tags') return Response.json({models:[{name:'translation-test:latest',digest:'v1',details:{format:'gguf'}}]});
    assert.equal(url.pathname,'/api/chat');
    const data=JSON.parse(init.body as string);
    const entries=JSON.parse(data.messages[1].content) as {id:number;text:string}[];
    return Response.json({message:{content:JSON.stringify({translations:entries.map(({id,text})=>({id,text:(ru[text] ?? text).replaceAll('25',corrupt?'73':'25')}))})}});
  });
  const first=await translateLesson(d,'ru',roots,new AbortController().signal);
  assert.equal(first.qualityReview?.state, 'pending');
  assert.equal(first.slides[0].body,'Взвесьте 25 зёрен.');
  assert.deepEqual(first.slides[0].bodyRuns,[{text:'Взвесьте ',bold:true},{text:'25 зёрен.',href}]);
  assert.equal(first.slides[0].notes,ru[s.notes]);
  assert.deepEqual(first.slides[0].image?.src,s.image?.src);
  assert.deepEqual(first.source,d.source);
  corrupt=true;
  await assert.rejects(translateLesson(d,'ru',roots,new AbortController().signal),/preserve a required value/);
  const count=worker.mock.callCount();
  await assert.rejects(translateLesson(d,'ru',roots,AbortSignal.abort()),{name:'AbortError'});
  assert.ok(worker.mock.callCount()<=count+1);
  assert.equal(s.body,'Weigh 25 grains.');
});
