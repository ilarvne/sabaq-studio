import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import sharp from 'sharp';
import JSZip from 'jszip';
import { brandContrast } from '@sabaq/lesson/themes';
import type { Deck, OrganizationAsset } from '@sabaq/lesson/types';
import { createStudioServer } from '../app';

test('organization role, published copies, style and retired media stay within their organization',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'studio-brand-'));
  const token='test-only-organization-token-00000000';
  const env={STUDIO_AUTH_MODE:process.env.STUDIO_AUTH_MODE,STUDIO_GATEWAY_SECRET:process.env.STUDIO_GATEWAY_SECRET};
  process.env.STUDIO_AUTH_MODE='gateway';process.env.STUDIO_GATEWAY_SECRET=token;
  const app=createStudioServer({dbPath:join(dir,'studio.sqlite'),mediaRoot:join(dir,'media')});
  t.after(async()=>{await app.close();for(const [key,value] of Object.entries(env)){if(value===undefined)delete process.env[key];else process.env[key]=value;}await rm(dir,{recursive:true,force:true});});
  const user=(subject:string,org='east',role='member')=>({'x-studio-gateway':token,'x-studio-org':org,'x-studio-user':subject,'x-studio-role':role});
  const admin=user('admin','east','org-admin'), teacher=user('teacher'), outsider=user('admin','west','org-admin'),other=user('other');
  const call=(method:'GET'|'POST'|'PUT'|'DELETE'|'PATCH',url:string,headers:ReturnType<typeof user>,payload?:Record<string,unknown>)=>app.inject({method,url,headers,payload});
  const create=async(headers:ReturnType<typeof user>)=>{
    const result=await call('POST','/api/decks',headers,{topic:'Light',template:'blank',language:'en',review:false,provider:'fixture',source:{name:'private.txt',text:'Private source'}});
    assert.equal(result.statusCode,201,result.body);return result.json<Deck>();
  };
  const old=await create(teacher);
  const before=(await call('GET','/api/capabilities',admin)).json();
  assert.equal(before.organizationAdmin,true);assert.equal(before.usageAdmin,false);
  assert.equal((await call('GET','/api/admin/usage',admin)).statusCode,403);
  assert.equal((await call('GET','/api/decks/'+old.id,admin)).statusCode,403);
  const png=await sharp({create:{width:50,height:20,channels:3,background:'#31536b'}}).png().toBuffer();
  const upload=(headers:ReturnType<typeof user>)=>app.inject({method:'POST',url:'/api/organization/media?name=School',headers:{...headers,'content-type':'application/octet-stream'},payload:png});
  assert.equal((await upload(teacher)).statusCode,403);
  const result=await upload(admin);assert.equal(result.statusCode,201,result.body);
  const logo=result.json<OrganizationAsset>();
  assert.equal((await call('GET',logo.src,teacher)).statusCode,200);
  assert.equal((await call('GET',logo.src,outsider)).statusCode,404);
  const style={paper:'#ffffff',ink:'#183951',font:'IBM Plex Sans',logoId:logo.id};
  assert.equal((await call('PUT','/api/organization/brand',teacher,style)).statusCode,403);
  assert.equal((await call('PUT','/api/organization/brand',outsider,style)).statusCode,404);
  assert.equal((await call('PUT','/api/organization/brand',admin,{...style,ink:'#dddddd'})).statusCode,422);
  assert.equal((await call('PUT','/api/organization/brand',admin,{...style,font:'arbitrary font'})).statusCode,400);
  assert.equal(brandContrast('#ffffff','#000000'),21);
  const savedStyle=(await call('PUT','/api/organization/brand',admin,style)).json();
  const original=await create(admin), independent=await create(outsider);
  assert.equal(independent.brand,undefined);assert.equal((await call('GET','/api/decks/'+old.id,teacher)).json<Deck>().brand,undefined);
  assert.deepEqual(original.brand,savedStyle);
  const url='/api/decks/'+original.id,slideId=original.slides[0].id;
  const edit=async(version:number,changes:Record<string,unknown>)=>(await call('PATCH',url,admin,{op:{kind:'slide',slideId,baseVersion:version,changes}})).json<Deck>();
  const first=await edit(0,{title:'Original',notes:'Teacher guidance',layout:'image-right',image:{src:logo.src,alt:'School image'}});
  const publish=(revision:number,headers=admin)=>call('POST','/api/organization/templates',headers,{deckId:original.id,revision,name:'Lab session'});
  assert.equal((await publish(first.revision,teacher)).statusCode,403);
  assert.equal((await publish(first.revision,outsider)).statusCode,403);
  const published=await publish(first.revision);assert.equal(published.statusCode,201,published.body);
  const id=published.json().id;
  assert.equal((await call('GET','/api/lesson-templates',teacher)).json()[0].id,id);
  assert.ok(!(await call('GET','/api/lesson-templates',outsider)).json().some((e:{id:string})=>e.id===id));
  const copy=(id:string,requestId:string,headers=teacher)=>call('POST','/api/organization/templates/'+id+'/copies',headers,{title:'Class A',requestId});
  assert.equal((await copy(id,crypto.randomUUID(),outsider)).statusCode,404);
  const key=crypto.randomUUID(), created=await copy(id,key);
  assert.equal(created.statusCode,201,created.body);const lesson=created.json<Deck>();
  assert.equal(lesson.viewerPermission,'owner');assert.equal(lesson.source,undefined);assert.equal(lesson.slides[0].notes,'Teacher guidance');
  assert.notEqual(lesson.slides[0].id,slideId);assert.equal(lesson.outline[0].id,lesson.slides[0].id);
  assert.deepEqual(lesson.brand,savedStyle);assert.equal((await copy(id,key)).json().id,lesson.id);
  const second=await edit(first.slides[0].version,{title:'Revised'});
  assert.equal((await publish(first.revision)).statusCode,409);
  const replacement=(await publish(second.revision)).json();
  assert.notEqual(replacement.id,id);assert.equal((await copy(id,crypto.randomUUID())).statusCode,404);
  assert.equal((await copy(replacement.id,crypto.randomUUID())).json<Deck>().slides[0].title,'Revised');
  assert.equal((await call('GET','/api/decks/'+lesson.id,teacher)).json<Deck>().slides[0].title,'Original');
  assert.equal((await call('DELETE','/api/organization/media/'+logo.id,outsider)).statusCode,404);
  assert.equal((await call('DELETE','/api/organization/media/'+logo.id,admin)).statusCode,200);
  assert.deepEqual((await call('GET','/api/organization',teacher)).json().assets,[]);
  assert.equal((await call('GET',logo.src,other)).statusCode,404);
  assert.equal((await call('GET',logo.src,teacher)).statusCode,200);
  assert.equal((await create(other)).brand?.logo,undefined);
  const retained=(await copy(replacement.id,crypto.randomUUID(),other)).json<Deck>();
  assert.equal(retained.brand?.logo,logo.src);
  assert.equal((await call('GET',logo.src,other)).statusCode,200);
  const exported=await call('GET','/api/decks/'+lesson.id+'/export/pptx',teacher);
  assert.equal(exported.statusCode,200,exported.body.slice(0,100));
  const zip=await JSZip.loadAsync(exported.rawPayload),slide=await zip.file('ppt/slides/slide1.xml')!.async('text');
  assert.match(slide,/Organization logo/);assert.match(slide,/183951/);assert.match(slide,/Arial/);
});
